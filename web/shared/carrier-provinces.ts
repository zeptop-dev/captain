export function carrierProvinceName(code?: string, language = 'en'): string {
  const index = carrierProvinceCodes.findIndex(value => value === code)
  if (index < 0) return ''
  const locale = /^(zh-TW|zh-HK|zh-Hant)/i.test(language) ? 'zh-TW' : /^zh/i.test(language) ? 'zh-CN' : language.split('-')[0]
  return (names[locale] ?? names.en)[index] ?? ''
}
export function carrierProvinceOptions(language: string) {
  return carrierProvinceCodes.map(value => ({ value, label: carrierProvinceName(value, language) }))
}
